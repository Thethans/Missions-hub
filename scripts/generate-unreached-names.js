#!/usr/bin/env node

// Generates the full "wall of names" for the homepage's Abyss chapter
// (src/components/story/ChapterAbyss.jsx) — every real unreached people
// group in the current dataset, not a curated sample. Unlike
// src/data/whisperNames.js (a hand-picked ~20-name subset chosen for how
// they read in an isolated, ephemeral whisper), this is deliberately
// exhaustive: the point of the wall is that it's overwhelming and
// un-curated, the same way WHISPER_NAMES's own header comment already
// distinguishes "real, never invented" from "hand-curated for one specific
// effect" — this is the real-and-uncurated half of that same data.
//
// Usage: node scripts/generate-unreached-names.js (run after fetch-jp
// populates public/data/people-groups.geojson; same source WorldMap.jsx,
// HeroBackground.jsx, and whisperNames.js all already read from).

import fs from 'fs';
import path from 'path';

const GEOJSON_PATH = path.resolve('public/data/people-groups.geojson');
const OUT_PATH = path.resolve('src/data/unreachedNames.js');

const geojson = JSON.parse(fs.readFileSync(GEOJSON_PATH, 'utf8'));

const names = geojson.features
  .filter((f) => f.properties.progressStatus === 'unreached')
  .map((f) => `${f.properties.name} — ${f.properties.country}`)
  // Same name+country pair can appear more than once in the raw pull
  // (distinct language/dialect entries Joshua Project tracks separately
  // sometimes collapse to an identical display string here) — de-duplicated
  // so the wall doesn't repeat itself.
  .filter((v, i, arr) => arr.indexOf(v) === i)
  .sort((a, b) => a.localeCompare(b));

const out = `// Every real unreached people group in the current dataset — generated by
// scripts/generate-unreached-names.js, do not hand-edit. Deliberately
// exhaustive (not curated — see src/data/whisperNames.js for the curated
// counterpart), for src/components/story/ChapterAbyss.jsx's "wall of
// names": ${names.length.toLocaleString()} names, alphabetical.
export const UNREACHED_NAMES = ${JSON.stringify(names, null, 2)};
`;

fs.writeFileSync(OUT_PATH, out);
console.log(`Wrote ${names.length.toLocaleString()} unreached group names to ${path.relative(process.cwd(), OUT_PATH)}`);
